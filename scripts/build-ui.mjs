// Bundles the MCP Apps view (ui/media-view.ts) and inlines it into
// ui/media-view.html, so the server can return one self-contained HTML file as
// ui://gateway-mcp/media.html. Writes lib/ui/media-view.generated.ts
// (gitignored). Runs before dev, build and typecheck (package.json).

import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const MARK = '/* bundled ui/media-view.ts */';

// ext-apps validates messages with zod, whose locale index pulls in every
// language (about 250 KB). Error messages only need English.
const zodEnglishOnly = {
  name: 'zod-english-only',
  setup(b) {
    b.onLoad({ filter: /node_modules[\\/]zod[\\/]v4[\\/]locales[\\/]index\.js$/ }, (args) => ({
      contents: 'export { default as en } from "./en.js";',
      resolveDir: dirname(args.path),
    }));
  },
};

const { outputFiles } = await build({
  entryPoints: [`${root}ui/media-view.ts`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  platform: 'browser',
  write: false,
  legalComments: 'none',
  plugins: [zodEnglishOnly],
});
// A literal "</script" inside the bundle would end the inline script early.
const script = outputFiles[0].text.replaceAll('</script', '<\\/script');

const template = await readFile(`${root}ui/media-view.html`, 'utf8');
if (!template.includes(MARK)) throw new Error(`ui/media-view.html has no "${MARK}" placeholder`);
const html = template.replace(MARK, () => script);

await writeFile(
  `${root}lib/ui/media-view.generated.ts`,
  `// Generated by scripts/build-ui.mjs from ui/media-view.html and ui/media-view.ts. Do not edit.\nexport const MEDIA_VIEW_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`ui: media view ${(html.length / 1024).toFixed(0)} KB`);
